// Live coverage harness: runs every suite in lab/suites against a disposable project and writes a coverage matrix.
// Usage: FLAX_PROJECT=D:/FlaxProjects/BridgeLab node lab/run.js [area-or-test-filter]
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { connect } from '../tests/client.js';
import { project } from '../src/bridge.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const filter = (process.argv[2] ?? '').toLowerCase();
if (!/BridgeLab|Lab|Sandbox|Test/i.test(project) && !process.env.FLAX_LAB_FORCE)
  throw Error(`Refusing to run destructive lab suites against ${project}. Point FLAX_PROJECT at a disposable project (or set FLAX_LAB_FORCE=1).`);

const { client, call } = await connect();
const wait = ms => new Promise(r => setTimeout(r, ms));
async function until(check, { timeout = 15000, every = 200, what = 'condition' } = {}) {
  const end = Date.now() + timeout;
  let last;
  while (Date.now() < end) { last = await check(); if (last) return last; await wait(every); }
  throw Error(`Timed out waiting for ${what}`);
}
const exec = async (code, usings) => (await call('exec', { code, usings })).value;
const lab = { call, exec, until, wait, client, project, tool: (name, args = {}) => client.callTool({ name: 'flax_' + name, arguments: args }) };

// Fresh scene per run so suites never depend on leftovers.
async function freshScene() {
  let status = await call('status');
  if (status.play) { await call('stop_play'); await until(async () => !(await call('status')).play, { what: 'play to stop' }); }
  if (status.stopped) await call('resume_control');
  for (const scene of (await call('status')).scenes) await call('unload_scene', { id: scene.id, discard: true });
  const dir = path.join(project, 'Content', 'Lab');
  await fs.rm(dir, { recursive: true, force: true });
  const created = await call('create_scene', { path: `Lab/Run_${Date.now()}.scene` });
  lab.sceneId = created.id;
  return created;
}

const suites = [];
for (const file of (await fs.readdir(path.join(here, 'suites'))).filter(f => f.endsWith('.js')).sort())
  suites.push(await import(new URL(`./suites/${file}`, import.meta.url)));

const results = [];
try {
  await until(async () => { try { const s = await call('status'); return !s.compiling; } catch { return false; } }, { timeout: 120000, what: 'editor bridge' });
  const status = await call('status');
  console.log(`Bridge ${status.version} | ${status.project}`);
  await freshScene();
  for (const suite of suites) {
    for (const test of suite.tests) {
      const label = `${suite.area} / ${test.name}`;
      if (filter && !label.toLowerCase().includes(filter)) continue;
      const started = Date.now();
      const entry = { area: suite.area, name: test.name };
      try {
        if (test.skip) { const reason = await test.skip(lab); if (reason) { Object.assign(entry, { status: 'skip', detail: reason }); results.push(entry); console.log(`SKIP ${label}: ${reason}`); continue; } }
        const detail = await test.run(lab);
        Object.assign(entry, { status: 'pass', detail });
        console.log(`PASS ${label} (${Date.now() - started} ms)`);
      } catch (e) {
        Object.assign(entry, { status: 'fail', error: e.message.slice(0, 2000) });
        console.log(`FAIL ${label}: ${e.message.split('\n').slice(0, 6).join('\n     ')}`);
        // A failed test may leave play mode running; later suites assume edit mode.
        const s = await call('status').catch(() => null);
        if (s?.play) { await call('stop_play').catch(() => {}); await until(async () => !(await call('status')).play, { what: 'play to stop' }).catch(() => {}); }
      }
      entry.ms = Date.now() - started;
      results.push(entry);
    }
  }
} finally {
  await client.close();
}

const counts = Object.fromEntries(['pass', 'fail', 'skip'].map(k => [k, results.filter(r => r.status === k).length]));
await fs.mkdir(path.join(here, 'results'), { recursive: true });
await fs.writeFile(path.join(here, 'results', 'latest.json'), JSON.stringify({ utc: new Date(), project, counts, results }, null, 2));
if (!filter) {
  const areas = [...new Set(results.map(r => r.area))];
  const icon = { pass: '✅', fail: '❌', skip: '⏭️' };
  const lines = ['# Bridge coverage', '', `Generated by \`node lab/run.js\` on ${new Date().toISOString().slice(0, 10)}: ${counts.pass} passed, ${counts.fail} failed, ${counts.skip} skipped.`, '',
    '| Area | Test | Result | Notes |', '| --- | --- | --- | --- |',
    ...areas.flatMap(area => results.filter(r => r.area === area).map(r => `| ${area} | ${r.name} | ${icon[r.status]} | ${(r.error ?? (typeof r.detail === 'string' ? r.detail : '')).split('\n')[0].replace(/\|/g, '\\|').slice(0, 140)} |`))];
  await fs.writeFile(path.join(here, 'COVERAGE.md'), lines.join('\n') + '\n');
}
console.log(`\n${counts.pass} passed, ${counts.fail} failed, ${counts.skip} skipped`);
process.exitCode = counts.fail ? 1 : 0;
